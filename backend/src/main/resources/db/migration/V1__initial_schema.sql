-- =====================================================================
-- Dispatch: initial schema
-- Enum-like columns are stored as VARCHAR with CHECK constraints so the
-- values stay readable in SQL while still being enforced by the database.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------
CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(16)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'OPERATOR'))
);

CREATE UNIQUE INDEX ux_users_email ON users (lower(email));

-- ---------------------------------------------------------------------
-- Monitored services
-- ---------------------------------------------------------------------
CREATE TABLE services
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(120)  NOT NULL,
    description       VARCHAR(1000),
    environment       VARCHAR(16)   NOT NULL,
    owner_team        VARCHAR(120),
    status            VARCHAR(16)   NOT NULL DEFAULT 'HEALTHY',
    status_changed_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_services_environment CHECK (environment IN ('PRODUCTION', 'STAGING', 'DEVELOPMENT')),
    CONSTRAINT ck_services_status CHECK (status IN ('HEALTHY', 'DEGRADED', 'DOWN'))
);

CREATE UNIQUE INDEX ux_services_name ON services (lower(name));

-- ---------------------------------------------------------------------
-- Devices (monitored endpoints that belong to a service)
-- ---------------------------------------------------------------------
CREATE TABLE devices
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier   VARCHAR(64)  NOT NULL,
    name         VARCHAR(120) NOT NULL,
    device_type  VARCHAR(64)  NOT NULL,
    service_id   BIGINT       NOT NULL REFERENCES services (id),
    location     VARCHAR(120),
    status       VARCHAR(16)  NOT NULL DEFAULT 'ONLINE',
    last_seen_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_devices_status CHECK (status IN ('ONLINE', 'DEGRADED', 'OFFLINE'))
);

CREATE UNIQUE INDEX ux_devices_identifier ON devices (upper(identifier));
CREATE INDEX ix_devices_service_id ON devices (service_id);
CREATE INDEX ix_devices_status ON devices (status);

-- ---------------------------------------------------------------------
-- Events received from devices, services and external sources
-- ---------------------------------------------------------------------
CREATE TABLE events
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type  VARCHAR(64)   NOT NULL,
    severity    VARCHAR(16)   NOT NULL,
    source_type VARCHAR(16)   NOT NULL,
    source_id   VARCHAR(128)  NOT NULL,
    service_id  BIGINT REFERENCES services (id),
    device_id   BIGINT REFERENCES devices (id),
    message     VARCHAR(1000) NOT NULL,
    metadata    JSONB         NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ   NOT NULL,
    received_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_events_severity CHECK (severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_events_source_type CHECK (source_type IN ('DEVICE', 'SERVICE', 'EXTERNAL'))
);

-- Keyset pagination for the event stream walks (occurred_at, id) in descending order.
CREATE INDEX ix_events_occurred_at ON events (occurred_at DESC, id DESC);
CREATE INDEX ix_events_type_occurred_at ON events (event_type, occurred_at DESC);
CREATE INDEX ix_events_severity_occurred_at ON events (severity, occurred_at DESC);
CREATE INDEX ix_events_service_occurred_at ON events (service_id, occurred_at DESC);
CREATE INDEX ix_events_device_occurred_at ON events (device_id, occurred_at DESC);

-- ---------------------------------------------------------------------
-- Alert rules: convert matching events into incidents
-- ---------------------------------------------------------------------
CREATE TABLE alert_rules
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(120)   NOT NULL,
    description         VARCHAR(1000),
    condition_type      VARCHAR(32)    NOT NULL,
    event_type          VARCHAR(64),
    metric_key          VARCHAR(64),
    comparison_operator VARCHAR(8),
    threshold           NUMERIC(18, 4),
    min_event_severity  VARCHAR(16),
    service_id          BIGINT REFERENCES services (id) ON DELETE CASCADE,
    incident_severity   VARCHAR(16)    NOT NULL,
    title_template      VARCHAR(200),
    recovery_event_type VARCHAR(64),
    auto_resolve        BOOLEAN        NOT NULL DEFAULT TRUE,
    enabled             BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_alert_rules_condition_type
        CHECK (condition_type IN ('EVENT_TYPE', 'METRIC_THRESHOLD', 'SEVERITY_AT_LEAST')),
    CONSTRAINT ck_alert_rules_operator CHECK (comparison_operator IN ('GT', 'GTE', 'LT', 'LTE')),
    CONSTRAINT ck_alert_rules_incident_severity CHECK (incident_severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_alert_rules_min_severity
        CHECK (min_event_severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_alert_rules_event_type_condition
        CHECK (condition_type <> 'EVENT_TYPE' OR event_type IS NOT NULL),
    CONSTRAINT ck_alert_rules_metric_condition
        CHECK (condition_type <> 'METRIC_THRESHOLD' OR (event_type IS NOT NULL AND metric_key IS NOT NULL
            AND comparison_operator IS NOT NULL AND threshold IS NOT NULL)),
    CONSTRAINT ck_alert_rules_severity_condition
        CHECK (condition_type <> 'SEVERITY_AT_LEAST' OR min_event_severity IS NOT NULL)
);

CREATE UNIQUE INDEX ux_alert_rules_name ON alert_rules (lower(name));
CREATE INDEX ix_alert_rules_event_type ON alert_rules (event_type);
CREATE INDEX ix_alert_rules_recovery_event_type ON alert_rules (recovery_event_type);

-- ---------------------------------------------------------------------
-- Incidents
-- ---------------------------------------------------------------------
CREATE TABLE incidents
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    description     TEXT,
    severity        VARCHAR(16)  NOT NULL,
    -- Numeric rank so incidents can be sorted by severity in SQL.
    severity_rank   INTEGER GENERATED ALWAYS AS (
        CASE severity WHEN 'CRITICAL' THEN 4 WHEN 'HIGH' THEN 3 WHEN 'MEDIUM' THEN 2 ELSE 1 END
        ) STORED,
    status          VARCHAR(16)  NOT NULL,
    -- Identifies "the same ongoing problem" (rule + source) for de-duplication.
    fingerprint     VARCHAR(255),
    rule_id         BIGINT REFERENCES alert_rules (id) ON DELETE SET NULL,
    source_event_id BIGINT REFERENCES events (id) ON DELETE SET NULL,
    service_id      BIGINT REFERENCES services (id),
    device_id       BIGINT REFERENCES devices (id),
    assignee_id     BIGINT REFERENCES users (id),
    created_by_id   BIGINT REFERENCES users (id),
    event_count     INTEGER      NOT NULL DEFAULT 0,
    last_event_at   TIMESTAMPTZ,
    acknowledged_at TIMESTAMPTZ,
    recovered_at    TIMESTAMPTZ,
    resolved_at     TIMESTAMPTZ,
    resolution_note TEXT,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_incidents_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incidents_status CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED')),
    CONSTRAINT ck_incidents_resolution CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL)),
    CONSTRAINT ck_incidents_event_count CHECK (event_count >= 0)
);

-- The database-level guarantee behind de-duplication:
-- at most one unresolved incident may exist per fingerprint.
CREATE UNIQUE INDEX ux_incidents_active_fingerprint ON incidents (fingerprint) WHERE status <> 'RESOLVED';

CREATE INDEX ix_incidents_status_severity ON incidents (status, severity_rank DESC, created_at DESC);
CREATE INDEX ix_incidents_created_at ON incidents (created_at DESC);
CREATE INDEX ix_incidents_service_id ON incidents (service_id);
CREATE INDEX ix_incidents_device_id ON incidents (device_id);
CREATE INDEX ix_incidents_assignee_id ON incidents (assignee_id);
CREATE INDEX ix_incidents_rule_id ON incidents (rule_id);
CREATE INDEX ix_incidents_resolved_at ON incidents (resolved_at) WHERE resolved_at IS NOT NULL;

-- ---------------------------------------------------------------------
-- Events that contributed to an incident (trigger, repeats, recovery)
-- ---------------------------------------------------------------------
CREATE TABLE incident_events
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT      NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    event_id    BIGINT      NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    relation    VARCHAR(16) NOT NULL,
    linked_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_incident_events_relation CHECK (relation IN ('TRIGGER', 'OCCURRENCE', 'RECOVERY')),
    CONSTRAINT ux_incident_events_pair UNIQUE (incident_id, event_id)
);

CREATE INDEX ix_incident_events_event_id ON incident_events (event_id);

-- ---------------------------------------------------------------------
-- Operator notes
-- ---------------------------------------------------------------------
CREATE TABLE incident_comments
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT      NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id   BIGINT      NOT NULL REFERENCES users (id),
    body        TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_incident_comments_body CHECK (char_length(body) BETWEEN 1 AND 5000)
);

CREATE INDEX ix_incident_comments_incident ON incident_comments (incident_id, created_at);

-- ---------------------------------------------------------------------
-- Audit trail of everything that happened to an incident
-- ---------------------------------------------------------------------
CREATE TABLE incident_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT       NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    actor_id    BIGINT REFERENCES users (id),
    action      VARCHAR(32)  NOT NULL,
    from_value  VARCHAR(120),
    to_value    VARCHAR(120),
    message     VARCHAR(500) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_incident_history_action CHECK (action IN (
        'CREATED', 'STATUS_CHANGED', 'SEVERITY_CHANGED', 'ASSIGNED', 'UNASSIGNED', 'COMMENT_ADDED',
        'RECOVERY_DETECTED', 'RECURRED', 'AUTO_RESOLVED', 'REOPENED'))
);

CREATE INDEX ix_incident_history_incident ON incident_history (incident_id, created_at);
